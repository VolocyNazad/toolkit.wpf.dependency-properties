namespace Toolkit.Wpf.DependencyProperties.Generator;

/// <summary>
/// Provides the attribute declarations that the generator adds to every consuming compilation.
/// </summary>
internal static class DependencyPropertyAttributeSource
{
    /// <summary>
    /// Gets the hint name of the generated attribute source.
    /// </summary>
    public const string HintName = "GenerateDependencyPropertyAttributes.g.cs";

    /// <summary>
    /// Gets the source of the attributes that mark dependency properties.
    /// </summary>
    /// <remarks>
    /// The attributes are internal, so each consuming assembly carries its own copy and the declarations never
    /// reach the public API of the assembly.
    /// </remarks>
    public const string Text = """
        // <auto-generated />
        #nullable enable

        namespace VolocyNazad.Wpf.DependencyProperties;

        /// <summary>
        /// Generates an instance dependency property, its CLR wrapper and its change callback wiring.
        /// </summary>
        [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
        internal sealed class GenerateDependencyPropertyAttribute<T> : global::System.Attribute
        {
            public GenerateDependencyPropertyAttribute(string name)
            {
                Name = name;
            }

            /// <summary>Gets the name of the generated dependency property.</summary>
            public string Name { get; }

            /// <summary>Gets or sets the name of the change callback method; the default is On{Name}Changed.</summary>
            public string? OnChanged { get; set; }

            /// <summary>Gets or sets the source of the default value; the default is null or default(T).</summary>
            public string? DefaultValueExpression { get; set; }

            /// <summary>Gets or sets whether the property is registered read-only.</summary>
            public bool IsReadOnly { get; set; }

            /// <summary>Gets or sets the WPF metadata options of the property.</summary>
            public global::System.Windows.FrameworkPropertyMetadataOptions Options { get; set; }

            /// <summary>Gets or sets the default update source trigger of the property.</summary>
            public global::System.Windows.Data.UpdateSourceTrigger DefaultUpdateSourceTrigger { get; set; }

            /// <summary>Gets or sets the category shown in the property browser.</summary>
            public string? Category { get; set; }

            /// <summary>Gets or sets the description shown in the property browser.</summary>
            public string? Description { get; set; }

            /// <summary>Gets or sets the type converter applied to the property.</summary>
            public global::System.Type? TypeConverter { get; set; }

            /// <summary>Gets or sets whether a reference type property is nullable.</summary>
            public bool IsNullable { get; set; }

            /// <summary>Gets or sets the XML documentation of the dependency property field.</summary>
            public string? XmlDocumentation { get; set; }

            /// <summary>Gets or sets the XML documentation of the CLR property.</summary>
            public string? PropertyXmlDocumentation { get; set; }
        }

        /// <summary>
        /// Generates an attached dependency property, its getter and setter, and its change callback wiring.
        /// </summary>
        [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
        internal sealed class GenerateAttachedDependencyPropertyAttribute<T> : global::System.Attribute
        {
            public GenerateAttachedDependencyPropertyAttribute(string name)
            {
                Name = name;
            }

            /// <summary>Gets the name of the generated dependency property.</summary>
            public string Name { get; }

            /// <summary>Gets or sets the name of the change callback method; the default is On{Name}Changed.</summary>
            public string? OnChanged { get; set; }

            /// <summary>Gets or sets the source of the default value; the default is null or default(T).</summary>
            public string? DefaultValueExpression { get; set; }

            /// <summary>Gets or sets whether the property is registered read-only.</summary>
            public bool IsReadOnly { get; set; }

            /// <summary>Gets or sets the WPF metadata options of the property.</summary>
            public global::System.Windows.FrameworkPropertyMetadataOptions Options { get; set; }

            /// <summary>Gets or sets the default update source trigger of the property.</summary>
            public global::System.Windows.Data.UpdateSourceTrigger DefaultUpdateSourceTrigger { get; set; }

            /// <summary>Gets or sets the type for which the property is browsable.</summary>
            public global::System.Type? BrowsableForType { get; set; }

            /// <summary>Gets or sets the category shown in the property browser.</summary>
            public string? Category { get; set; }

            /// <summary>Gets or sets the description shown in the property browser.</summary>
            public string? Description { get; set; }

            /// <summary>Gets or sets the type converter applied to the property.</summary>
            public global::System.Type? TypeConverter { get; set; }

            /// <summary>Gets or sets whether a reference type property is nullable.</summary>
            public bool IsNullable { get; set; }

            /// <summary>Gets or sets the XML documentation of the dependency property field.</summary>
            public string? XmlDocumentation { get; set; }

            /// <summary>Gets or sets the XML documentation of the generated getter.</summary>
            public string? GetterXmlDocumentation { get; set; }

            /// <summary>Gets or sets the XML documentation of the generated setter.</summary>
            public string? SetterXmlDocumentation { get; set; }
        }
        """;
}
