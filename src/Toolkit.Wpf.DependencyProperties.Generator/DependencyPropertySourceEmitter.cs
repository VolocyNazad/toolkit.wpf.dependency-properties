using System.Text;

namespace Toolkit.Wpf.DependencyProperties.Generator;

// Each line of the generated source is written as its own statement so the emitted code reads like
// the code it replaces; the method-chaining suggestion of Roslynator would work against that.
#pragma warning disable RCS1201

/// <summary>
/// Writes the source of the generated dependency properties of one declaring type.
/// </summary>
internal static class DependencyPropertySourceEmitter
{
    private const string DependencyPropertyType = "global::System.Windows.DependencyProperty";
    private const string DependencyObjectType = "global::System.Windows.DependencyObject";
    private const string EventArgsType = "global::System.Windows.DependencyPropertyChangedEventArgs";
    private const string FrameworkMetadataType = "global::System.Windows.FrameworkPropertyMetadata";
    private const string MetadataType = "global::System.Windows.PropertyMetadata";
    private const string OptionsType = "global::System.Windows.FrameworkPropertyMetadataOptions";
    private const string CategoryAttribute = "global::System.ComponentModel.CategoryAttribute";
    private const string DescriptionAttribute = "global::System.ComponentModel.DescriptionAttribute";
    private const string TypeConverterAttribute = "global::System.ComponentModel.TypeConverterAttribute";
    private const string BrowsableForTypeAttribute = "global::System.Windows.AttachedPropertyBrowsableForTypeAttribute";

    /// <summary>
    /// Writes the generated source of the supplied dependency properties of one declaring type.
    /// </summary>
    /// <param name="properties">The dependency properties of one declaring type, in declaration order.</param>
    /// <returns>The generated C# source.</returns>
    public static string Emit(IReadOnlyList<DependencyPropertyModel> properties)
    {
        DependencyPropertyModel first = properties[0];
        StringBuilder source = new();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        if (first.Namespace.Length > 0)
        {
            source.AppendLine($"namespace {first.Namespace};");
            source.AppendLine();
        }

        source.AppendLine($"{first.Accessibility} {(first.IsStatic ? "static " : string.Empty)}partial class {first.TypeName}");
        source.AppendLine("{");

        for (int index = 0; index < properties.Count; index++)
        {
            if (index > 0) source.AppendLine();
            AppendProperty(source, properties[index]);
        }

        source.AppendLine("}");
        return source.ToString();
    }

    private static void AppendProperty(StringBuilder source, DependencyPropertyModel property)
    {
        AppendDocumentation(source, property.XmlDocumentation ?? FieldDefaultDocumentation(property));
        AppendRegistration(source, property);

        source.AppendLine();

        if (property.IsAttached)
            AppendAttachedAccessors(source, property);
        else
            AppendInstanceProperty(source, property);

        if (property.CallbackKind != CallbackKind.StaticMethod) AppendHooks(source, property);
        if (property.CallbackKind is CallbackKind.NewValueHook or CallbackKind.ValuesHook) AppendCallbackWrapper(source, property);
    }

    private static void AppendRegistration(StringBuilder source, DependencyPropertyModel property)
    {
        string registerMethod;
        if (property.IsAttached)
            registerMethod = property.IsReadOnly ? "RegisterAttachedReadOnly" : "RegisterAttached";
        else
            registerMethod = property.IsReadOnly ? "RegisterReadOnly" : "Register";

        if (property.IsReadOnly)
        {
            source.AppendLine($"    private static readonly global::System.Windows.DependencyPropertyKey {property.Name}PropertyKey =");
            source.AppendLine($"        {DependencyPropertyType}.{registerMethod}(");
            AppendRegistrationArguments(source, property, "            ");
            source.AppendLine($"    public static readonly {DependencyPropertyType} {property.Name}Property = {property.Name}PropertyKey.DependencyProperty;");
            return;
        }

        source.AppendLine($"    public static readonly {DependencyPropertyType} {property.Name}Property =");
        source.AppendLine($"        {DependencyPropertyType}.{registerMethod}(");
        AppendRegistrationArguments(source, property, "            ");
    }

    private static void AppendRegistrationArguments(StringBuilder source, DependencyPropertyModel property, string indent)
    {
        source.AppendLine($"{indent}name: \"{property.Name}\",");
        source.AppendLine($"{indent}propertyType: {property.PropertyTypeExpression},");
        source.AppendLine($"{indent}ownerType: typeof({property.TypeDisplayName}),");
        AppendMetadata(source, property, indent);
        source.AppendLine($"{indent}validateValueCallback: {property.ValidateCallbackName ?? "null"});");
    }

    private static void AppendMetadata(StringBuilder source, DependencyPropertyModel property, string indent)
    {
        bool isFrameworkMetadata = property.OptionsExpression.Length > 0
            || property.UpdateSourceTriggerExpression.Length > 0
            || property.CoerceCallbackName is not null;
        string metadataType = isFrameworkMetadata ? FrameworkMetadataType : MetadataType;
        string metadataArgument = property.IsAttached ? "defaultMetadata" : "typeMetadata";

        source.AppendLine($"{indent}{metadataArgument}: new {metadataType}(");
        source.AppendLine($"{indent}    defaultValue: {DefaultValueExpression(property)},");
        if (!isFrameworkMetadata)
        {
            source.AppendLine($"{indent}    propertyChangedCallback: {CallbackExpression(property)}),");
            return;
        }

        source.AppendLine($"{indent}    flags: {OptionsExpression(property)},");
        source.AppendLine($"{indent}    propertyChangedCallback: {CallbackExpression(property)},");
        source.AppendLine($"{indent}    coerceValueCallback: {property.CoerceCallbackName ?? "null"},");
        source.AppendLine($"{indent}    isAnimationProhibited: false{(property.UpdateSourceTriggerExpression.Length > 0 ? "," : "),")}");
        if (property.UpdateSourceTriggerExpression.Length > 0)
            source.AppendLine($"{indent}    defaultUpdateSourceTrigger: {property.UpdateSourceTriggerExpression}),");
    }

    private static void AppendInstanceProperty(StringBuilder source, DependencyPropertyModel property)
    {
        AppendDocumentation(source, property.ValueXmlDocumentation ?? ValueDefaultDocumentation(property));
        AppendMemberAttributes(source, property);
        source.AppendLine($"    public {property.PropertyType} {property.Name}");
        source.AppendLine("    {");
        source.AppendLine($"        get => ({property.PropertyType})GetValue({property.Name}Property);");
        if (property.IsReadOnly)
        {
            string setterAccessibility = property.IsSealed ? "private" : "protected";
            source.AppendLine($"        {setterAccessibility} set => SetValue({property.Name}Property, value);");
        }
        else
        {
            source.AppendLine($"        set => SetValue({property.Name}Property, value);");
        }

        source.AppendLine("    }");
    }

    private static void AppendAttachedAccessors(StringBuilder source, DependencyPropertyModel property)
    {
        AppendDocumentation(source, property.ValueXmlDocumentation ?? GetterDefaultDocumentation(property));
        if (property.BrowsableForTypeExpression is not null)
            source.AppendLine($"    [{BrowsableForTypeAttribute}({property.BrowsableForTypeExpression})]");
        AppendMemberAttributes(source, property);
        source.AppendLine($"    public static {property.PropertyType} Get{property.Name}({DependencyObjectType} element) =>");
        source.AppendLine($"        ({property.PropertyType})element.GetValue({property.Name}Property);");
        source.AppendLine();

        AppendDocumentation(source, property.SetterXmlDocumentation ?? SetterDefaultDocumentation(property));
        string setterAccessibility = property.IsReadOnly ? "private" : "public";
        source.AppendLine($"    {setterAccessibility} static void Set{property.Name}({DependencyObjectType} element, {property.PropertyType} value) =>");
        source.AppendLine($"        element.SetValue({property.Name}Property, value);");
    }

    private static void AppendHooks(StringBuilder source, DependencyPropertyModel property)
    {
        string modifier = property.IsAttached ? "static partial void" : "partial void";
        source.AppendLine();
        source.AppendLine($"    {modifier} {property.CallbackName}({property.PropertyType} oldValue, {property.PropertyType} newValue);");
        source.AppendLine();
        source.AppendLine($"    {modifier} {property.CallbackName}({property.PropertyType} newValue);");
    }

    private static void AppendCallbackWrapper(StringBuilder source, DependencyPropertyModel property)
    {
        string call = property.CallbackKind == CallbackKind.ValuesHook
            ? ArgumentPair(property)
            : $"({property.PropertyType})args.NewValue";
        string invocation = property.IsAttached
            ? $"{property.CallbackName}({call})"
            : $"(({property.TypeDisplayName})sender).{property.CallbackName}({call})";

        source.AppendLine();
        source.AppendLine($"    private static void {property.CallbackName}({DependencyObjectType} sender, {EventArgsType} args)");
        source.AppendLine("    {");
        source.AppendLine($"        {invocation};");
        source.AppendLine("    }");
    }

    private static string ArgumentPair(DependencyPropertyModel property)
    {
        return $"({property.PropertyType})args.OldValue, ({property.PropertyType})args.NewValue";
    }

    private static void AppendMemberAttributes(StringBuilder source, DependencyPropertyModel property)
    {
        if (property.Category is not null)
            source.AppendLine($"    [{CategoryAttribute}(\"{Escape(property.Category)}\")]");
        if (property.Description is not null)
            source.AppendLine($"    [{DescriptionAttribute}(\"{Escape(property.Description)}\")]");
        if (property.TypeConverterExpression is not null)
            source.AppendLine($"    [{TypeConverterAttribute}({property.TypeConverterExpression})]");
    }

    private static void AppendDocumentation(StringBuilder source, string documentation)
    {
        if (string.IsNullOrWhiteSpace(documentation)) return;
        foreach (string line in documentation.Replace("\r\n", "\n").Split('\n'))
        {
            string trimmed = line.Trim();
            source.AppendLine(trimmed.Length == 0 ? "    ///" : $"    /// {trimmed}");
        }
    }

    private static string FieldDefaultDocumentation(DependencyPropertyModel property)
    {
        return property.IsAttached
            ? $"<summary>Identifies the <see cref=\"{property.Name}Property\"/> attached dependency property.</summary>"
            : $"<summary>Identifies the <see cref=\"{property.Name}\"/> dependency property.</summary>";
    }

    private static string ValueDefaultDocumentation(DependencyPropertyModel property)
    {
        return $"<summary>Gets or sets the value of the <see cref=\"{property.Name}Property\"/> dependency property.</summary>";
    }

    private static string GetterDefaultDocumentation(DependencyPropertyModel property)
    {
        return $"<summary>Gets the value of the <see cref=\"{property.Name}Property\"/> attached property.</summary>\n"
            + "<param name=\"element\">The element that carries the property.</param>\n"
            + "<returns>The property value.</returns>";
    }

    private static string SetterDefaultDocumentation(DependencyPropertyModel property)
    {
        return $"<summary>Sets the value of the <see cref=\"{property.Name}Property\"/> attached property.</summary>\n"
            + "<param name=\"element\">The element that carries the property.</param>\n"
            + "<param name=\"value\">The property value.</param>";
    }

    private static string DefaultValueExpression(DependencyPropertyModel property)
    {
        if (property.DefaultValueExpression.Length > 0) return property.DefaultValueExpression;
        return property.IsReferenceType ? "null" : $"default({property.PropertyType})";
    }

    private static string OptionsExpression(DependencyPropertyModel property)
    {
        return property.OptionsExpression.Length > 0 ? property.OptionsExpression : $"{OptionsType}.None";
    }

    private static string CallbackExpression(DependencyPropertyModel property)
    {
        return property.CallbackKind switch
        {
            CallbackKind.StaticMethod or CallbackKind.NewValueHook or CallbackKind.ValuesHook => property.CallbackName,
            CallbackKind.None => "null",
            _ => "null",
        };
    }

    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}

#pragma warning restore RCS1201
